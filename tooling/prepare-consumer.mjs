import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { copyFileSync, cpSync, existsSync, lstatSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const seed = path.join(root, "examples/nestjs");
const output = path.join(root, "built/typers");
const consumer = path.join(output, "consumer");
const markerName = ".typers-generated-consumer";
const markerContents = "Generated by tooling/prepare-consumer.mjs; safe to recreate.\n";
const localPackages = [
  { dependency: "typescript", directory: "compiler", group: "devDependencies" },
  { dependency: "@typers/core", directory: "core", group: "dependencies" },
];
const localKeys = new Set(localPackages.map(({ dependency }) => `node_modules/${dependency}`));
const digest = (contents, algorithm = "sha256", encoding = "hex") =>
  createHash(algorithm).update(contents).digest(encoding);

function externalEntries(lock) {
  return Object.fromEntries(Object.entries(lock.packages).filter(([key]) => key !== "" && !localKeys.has(key)));
}

function recreateOwnedConsumer() {
  if (existsSync(consumer)) {
    assert.equal(lstatSync(consumer).isSymbolicLink(), false, "Refusing to replace a symlink at the consumer path");
    const marker = path.join(consumer, markerName);
    assert.ok(existsSync(marker), `Refusing to remove an unmarked directory: ${consumer}`);
    assert.equal(readFileSync(marker, "utf8"), markerContents, "Unexpected consumer ownership marker");
    rmSync(consumer, { recursive: true });
  }
  mkdirSync(consumer, { recursive: true });
  writeFileSync(path.join(consumer, markerName), markerContents);
}

/** Install current local artifacts while preserving every external lock entry. */
export function prepareConsumer() {
  const seedLockBytes = readFileSync(path.join(seed, "package-lock.json"));
  const lock = JSON.parse(seedLockBytes);
  assert.equal(lock.lockfileVersion, 3, "Expected the checked-in npm v3 fixture lockfile");
  const externalBefore = structuredClone(externalEntries(lock));
  const manifest = JSON.parse(readFileSync(path.join(seed, "package.json"), "utf8"));
  assert.ok(lock.packages[""], "The fixture lockfile is missing its root package");

  recreateOwnedConsumer();
  for (const file of ["tsconfig.json", "tsconfig.typers.json", "nest-cli.json", "src"]) {
    cpSync(path.join(seed, file), path.join(consumer, file), { recursive: true });
  }
  mkdirSync(path.join(consumer, "artifacts"));

  const artifacts = [];
  for (const { dependency, directory, group } of localPackages) {
    const metadata = JSON.parse(readFileSync(path.join(root, "packages", directory, "package.json"), "utf8"));
    assert.deepEqual(metadata.dependencies ?? {}, {}, "Local package dependencies require an updated fixture lock contract");
    assert.deepEqual(metadata.optionalDependencies ?? {}, {}, "Local optional dependencies require an updated fixture lock contract");
    assert.deepEqual(metadata.peerDependencies ?? {}, {}, "Local peer dependencies require an updated fixture lock contract");
    assert.ok(manifest[group]?.[dependency]?.startsWith("file:"), `Expected a local fixture dependency: ${dependency}`);
    assert.ok(lock.packages[`node_modules/${dependency}`], `Missing seed lock entry for ${dependency}`);

    const basename = `${metadata.name.replace(/^@/, "").replaceAll("/", "-")}-${metadata.version}`;
    const tarball = path.join(output, `${basename}.tgz`);
    const bytes = readFileSync(tarball);
    const sha256 = digest(bytes);
    const integrity = `sha512-${digest(bytes, "sha512", "base64")}`;
    const filename = `${basename}-${sha256}.tgz`;
    const spec = `file:artifacts/${filename}`;
    copyFileSync(tarball, path.join(consumer, "artifacts", filename));

    manifest[group][dependency] = spec;
    lock.packages[""][group][dependency] = spec;
    lock.packages[`node_modules/${dependency}`] = {
      name: metadata.name,
      version: metadata.version,
      resolved: spec,
      integrity,
      ...(group === "devDependencies" ? { dev: true } : {}),
      ...(metadata.license ? { license: metadata.license } : {}),
      ...(metadata.bin ? { bin: metadata.bin } : {}),
      ...(metadata.engines ? { engines: metadata.engines } : {}),
    };
    artifacts.push({ dependency, name: metadata.name, version: metadata.version, filename, sha256, integrity });
  }

  assert.deepEqual(externalEntries(lock), externalBefore, "External dependency locks changed during local artifact preparation");
  writeFileSync(path.join(consumer, "package.json"), JSON.stringify(manifest, null, 2) + "\n");
  writeFileSync(path.join(consumer, "package-lock.json"), JSON.stringify(lock, null, 2) + "\n");
  const npm = process.platform === "win32" ? "npm.cmd" : "npm";
  execFileSync(npm, ["ci", "--ignore-scripts", "--no-audit", "--no-fund", "--include=dev"], {
    cwd: consumer,
    stdio: "inherit",
  });
  const installedLock = JSON.parse(readFileSync(path.join(consumer, "package-lock.json"), "utf8"));
  assert.deepEqual(installedLock, lock, "npm ci changed the prepared lockfile");

  const verifiedFiles = {};
  const executable = process.platform === "win32" ? "typers.exe" : "typers";
  const packageFiles = {
    compiler: ["package.json", "build-info.json", `native/${executable}`, "bin/typers.cjs", "lib/version.cjs", "lib/version.d.cts"],
    core: ["package.json", "dist/esm/index.js", "dist/esm/index.d.ts", "dist/cjs/index.js", "dist/cjs/index.d.ts", "dist/cjs/package.json"],
  };
  for (const { dependency, directory } of localPackages) {
    for (const file of packageFiles[directory]) {
      const expected = digest(readFileSync(path.join(root, "packages", directory, file)));
      const actual = digest(readFileSync(path.join(consumer, "node_modules", dependency, file)));
      assert.equal(actual, expected, `Installed artifact is stale or altered: ${dependency}/${file}`);
      verifiedFiles[`${dependency}/${file}`] = actual;
    }
  }
  assert.equal(
    digest(readFileSync(path.join(root, "tsc/built/local", executable))),
    verifiedFiles[`typescript/native/${executable}`],
    "Installed compiler does not match the current native build",
  );
  assert.equal(digest(readFileSync(path.join(seed, "package-lock.json"))), digest(seedLockBytes), "The checked-in fixture lockfile was modified");
  console.log(`Fresh consumer installed at ${consumer}`);
  return {
    directory: consumer,
    seedLockSha256: digest(seedLockBytes),
    externalLockSha256: digest(JSON.stringify(externalBefore)),
    artifacts,
    verifiedFiles,
  };
}
